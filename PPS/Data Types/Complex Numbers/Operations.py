# Create two complex numbers and display their addition, subtraction, multiplication, and division.

num1 = 2 + 3j
num2 = 1 + 2j

add = num1 + num2
sub = num1 - num2
mul = num1 * num2
div = num1 / num2

print(f"Addition: {add}")
print(f"Subtraction: {sub}")
print(f"Multiplication: {mul}")
print(f"Division: {div}")